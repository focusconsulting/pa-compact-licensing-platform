// Writes src/api/mocks.ts from engineering/api/openapi.json: one MSW handler per
// operation, answering with its success status and a body built from the
// examples on the API's response models. Run through `pnpm generate`.
import { readFileSync, writeFileSync } from "node:fs";

const document = JSON.parse(
  readFileSync(new URL("../../api/openapi.json", import.meta.url), "utf8"),
);
const { schemas } = document.components;

const PRIMITIVES = {
  boolean: true,
  integer: 1,
  number: 1,
  null: null,
  string: "string",
};

const nullable = (schema) => schema.anyOf?.some((s) => s.type === "null");

function example(schema) {
  if (schema.$ref) return example(schemas[schema.$ref.split("/").pop()]);
  if (schema.examples && schema.type === "object") {
    // FastAPI drops null values from examples, so a missing nullable field is null.
    const [given] = schema.examples;
    return Object.fromEntries(
      Object.entries(schema.properties).map(([name, property]) => {
        if (name in given) return [name, given[name]];
        return [name, nullable(property) ? null : example(property)];
      }),
    );
  }
  if (schema.examples) return schema.examples[0];
  if (schema.anyOf) {
    return example(
      schema.anyOf.find((s) => s.type !== "null") ?? schema.anyOf[0],
    );
  }
  if (schema.type === "array") return [example(schema.items)];
  if (schema.type === "object") {
    return Object.fromEntries(
      Object.entries(schema.properties ?? {}).map(([name, property]) => [
        name,
        example(property),
      ]),
    );
  }
  return PRIMITIVES[schema.type] ?? null;
}

function handler(path, method, operation) {
  const [status, response] = Object.entries(operation.responses).find(
    ([code]) => code.startsWith("2"),
  );
  const url = `*${path.replace(/\{(\w+)\}/g, ":$1")}`;
  const schema = response.content?.["application/json"]?.schema;
  const body = schema
    ? `HttpResponse.json(${JSON.stringify(example(schema))}, { status: ${status} })`
    : `new HttpResponse(null, { status: ${status} })`;
  return `  // ${operation.summary ?? operation.operationId}\n  http.${method}("${url}", () => ${body}),`;
}

const handlers = Object.entries(document.paths).flatMap(([path, operations]) =>
  Object.entries(operations).map(([method, operation]) =>
    handler(path, method, operation),
  ),
);

writeFileSync(
  new URL("../src/api/mocks.ts", import.meta.url),
  `// Generated by \`pnpm generate\` from engineering/api/openapi.json. Do not edit.
import { http, HttpResponse } from "msw";

/** One handler per API operation, answering with the API's response examples. */
export const handlers = [
${handlers.join("\n")}
];
`,
);
